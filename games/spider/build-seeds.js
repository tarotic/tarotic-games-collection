/*
 * Offline builder for the winnable-deal bank (seeds.js).
 *
 * Searches seeds with the solver and keeps only deals where a winning line
 * was found. Each entry stores the seed plus the winning moves, so the
 * game can show winnable deals instantly and the tests can replay them.
 *
 * Usage:  node games/spider/build-seeds.js
 * Slow for 4 suits (tens of seconds per solved deal). Output: games/spider/seeds.js
 */
const fs = require("node:fs");
const path = require("node:path");
const Spider = require("./spider-core.js");

const TARGETS = { 1: 30, 2: 30, 4: 15 };
const BUDGETS = { 1: 200000, 2: 600000, 4: 1200000 };
const OUT = path.join(__dirname, "seeds.js");

function encodeMoves(moves) {
  return moves
    .map((m) => (m.type === "deal" ? "D" : `${m.from}.${m.count}.${m.to}`))
    .join(" ");
}

function writeBank(bank) {
  const body = JSON.stringify(bank, null, 1);
  const text = `/* Generated by build-seeds.js. Every entry is a winnable deal; do not edit by hand. */
(function (root) {
  root.SpiderSeedBank = ${body};
})(typeof self !== "undefined" ? self : globalThis);
if (typeof module === "object" && module.exports) {
  module.exports = (typeof self !== "undefined" ? self : globalThis).SpiderSeedBank;
}
`;
  fs.writeFileSync(OUT, text);
}

const bank = { 1: [], 2: [], 4: [] };
const started = Date.now();
for (const suitCount of [1, 2, 4]) {
  let seed = 1;
  while (bank[suitCount].length < TARGETS[suitCount]) {
    const state = Spider.newGame(suitCount, seed);
    const solution = Spider.solve(state, { budget: BUDGETS[suitCount] });
    if (solution) {
      bank[suitCount].push({ seed, moves: encodeMoves(solution) });
      writeBank(bank); // save progress after every solved deal
      const secs = ((Date.now() - started) / 1000).toFixed(0);
      console.log(`${suitCount}-suit: seed ${seed} solved (${solution.length} moves) [${bank[suitCount].length}/${TARGETS[suitCount]}] ${secs}s`);
    }
    seed++;
  }
}
console.log(`Done. Wrote ${OUT}`);
