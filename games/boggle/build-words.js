/*
 * Builds games/boggle/words.js from a plain word list (one word per line).
 *
 *   node games/boggle/build-words.js <path-to-wordlist.txt>
 *
 * Source used: the ENABLE word list (public domain),
 * https://github.com/dolph/dictionary/blob/master/enable1.txt
 * Only words of 3 to 16 letters with a-z characters are kept. 16 is the
 * longest path a 4x4 board can spell, so longer words can never be traced.
 */
const fs = require("fs");
const path = require("path");

const MIN_LENGTH = 3;
const MAX_LENGTH = 16;

const input = process.argv[2];
if (!input) {
  console.error("usage: node games/boggle/build-words.js <wordlist.txt>");
  process.exit(1);
}

const words = new Set();
for (const raw of fs.readFileSync(input, "utf8").split(/\r?\n/)) {
  const word = raw.trim().toLowerCase();
  if (word.length >= MIN_LENGTH && word.length <= MAX_LENGTH && /^[a-z]+$/.test(word)) {
    words.add(word);
  }
}

const sorted = [...words].sort();
const body = [
  "/*",
  " * Generated by build-words.js from the ENABLE word list (public domain).",
  " * Do not edit by hand. Rebuild with: node games/boggle/build-words.js <wordlist.txt>",
  ` * ${sorted.length} words, ${MIN_LENGTH} to ${MAX_LENGTH} letters, a-z only.`,
  " */",
  "(function (root, factory) {",
  "  const api = factory();",
  "  if (typeof module === \"object\" && module.exports) {",
  "    module.exports = api;",
  "  } else {",
  "    root.BoggleWords = api;",
  "  }",
  "})(typeof self !== \"undefined\" ? self : globalThis, function () {",
  "  return `" + sorted.join("\n") + "`;",
  "});",
  "",
].join("\n");

const outFile = path.join(__dirname, "words.js");
fs.writeFileSync(outFile, body);
console.log(`wrote ${sorted.length} words to ${outFile}`);
